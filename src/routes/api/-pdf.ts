function buildTreatmentPlanPDF(
  plan: TreatmentPlan,
  client: Client | null,
  assessment: Assessment | null,
): Uint8Array {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const today = fmtDate(new Date().toISOString());
  const pageWidth = doc.internal.pageSize.width;
  let y = 30;

  const concurrent = parseJson<{ service: string; provider: string; frequency?: string }[]>(plan.concurrent_services, []);
  const behaviors = parseJson<{ behavior: string; topography: string; frequency: string; intensity: string; duration: string }[]>(plan.maladaptive_behaviors, []);
  const goals = parseJson<{ domain: string; description: string; measurement: string; baseline: string; target: string; target_date: string }[]>(plan.skill_acquisition_goals, []);
  const parentGoals = parseJson<{ goal: string; method: string; frequency: string }[]>(plan.parent_training_goals, []);
  const coordGoals = parseJson<{ provider: string; goal: string; method: string }[]>(plan.service_coordination_goals, []);
  const services = parseJson<{ service_name: string; cpt_code: string; frequency: string; duration: string; hours_per_week?: number }[]>(plan.requested_services, []);
  const schedule = parseJson<{ day: string; time: string; location: string; service_type: string }[]>(plan.therapy_schedule, []);

  // --- Cover Page ---
  addHeader(doc, "ClearView ABA Suite");
  // Centered cover content
  const centerX = pageWidth / 2;
  doc.setFontSize(22);
  doc.setTextColor(17, 24, 39);
  doc.setFont("helvetica", "bold");
  doc.text("Individualized Treatment Plan", centerX, 80, { align: "center" });

  doc.setFontSize(14);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(55, 65, 81);
  doc.text(`Prepared for: ${client?.name ?? "—"}`, centerX, 100, { align: "center" });

  doc.setFontSize(10);
  doc.setTextColor(107, 114, 128);
  const coverInfo = [
    `Date: ${today}`,
    `BCBA: ${assessment?.assessor_name ?? "—"}`,
    `Plan Status: ${plan.status}`,
    `Generated by ClearView ABA Suite`,
  ];
  let cy = 115;
  for (const line of coverInfo) {
    doc.text(line, centerX, cy, { align: "center" });
    cy += 6;
  }

  // --- Section 1: Client Identification ---
  doc.addPage();
  y = 30;
  addHeader(doc, "Treatment Plan — Detail");
  y = 32;
  doc.setFontSize(9);
  doc.setTextColor(75, 85, 99);
  doc.text(`Date Generated: ${today}`, 14, y);

  y = addSectionTitle(doc, "Section 1: Client Identification & Background", y + 5);
  const ident: [string, string][] = [
    ["Client Name", client?.name ?? "—"],
    ["Date of Birth", client?.date_of_birth ? fmtDate(client.date_of_birth) : "—"],
    ["Gender", client?.gender ?? "—"],
    ["Contact", client?.contact_email ?? client?.contact_phone ?? "—"],
    ["Address", client?.address ?? "—"],
    ["Referral Source", client?.referral_source ?? "—"],
    ["Reason for Referral", plan.reason_for_referral ?? "—"],
  ];
  for (const [l, v] of ident) {
    doc.setFontSize(9);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(55, 65, 81);
    doc.text(`${l}:`, 14, y);
    doc.setFont("helvetica", "normal");
    doc.text(v, 55, y);
    y += 5;
  }

  // --- Section 2: Diagnosis & Treatment History ---
  y = addSectionTitle(doc, "Section 2: Diagnosis & Treatment History", y + 3);
  doc.setFontSize(9);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(55, 65, 81);
  doc.text("Diagnosis:", 14, y);
  doc.setFont("helvetica", "normal");
  doc.text(plan.diagnosis || "—", 48, y, { maxWidth: pageWidth - 62 });
  y += 6;

  doc.setFont("helvetica", "bold");
  doc.text("Treatment History:", 14, y);
  doc.setFont("helvetica", "normal");
  const thLines = doc.splitTextToSize(plan.treatment_history || "—", pageWidth - 28);
  doc.text(thLines, 14, y + 5);
  y += 5 + thLines.length * 4.5 + 4;

  // --- Section 3: Concurrent Services ---
  y = addSectionTitle(doc, "Section 3: Concurrent Services", y + 2);
  if (concurrent.length > 0) {
    const cRows = concurrent.map((c) => [c.service || "—", c.provider || "—", c.frequency || "—"]);
    autoTable(doc, {
      head: [["Service", "Provider", "Frequency"]],
      body: cRows,
      startY: y,
      theme: "grid",
      styles: { fontSize: 8, cellPadding: 2 },
      headStyles: { fillColor: [79, 70, 229], textColor: 255, fontStyle: "bold" },
      margin: { left: 14, right: 14 },
    });
    y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 6;
    y += 4;
  } else {
    doc.setFontSize(9);
    doc.setTextColor(107, 114, 128);
    doc.text("No concurrent services listed.", 14, y);
    y += 8;
  }

  // --- Section 4: Family & School ---
  y = addSectionTitle(doc, "Section 4: Family & School Information", y + 2);
  doc.setFontSize(9);
  doc.setFont("helvetica", "bold");
  doc.text("Family History:", 14, y);
  doc.setFont("helvetica", "normal");
  const fhLines = doc.splitTextToSize(plan.family_history || "—", pageWidth - 28);
  doc.text(fhLines, 14, y + 5);
  y += 5 + fhLines.length * 4.5 + 4;

  doc.setFont("helvetica", "bold");
  doc.text("School Information:", 14, y);
  doc.setFont("helvetica", "normal");
  const siLines = doc.splitTextToSize(plan.school_info || "—", pageWidth - 28);
  doc.text(siLines, 14, y + 5);
  y += 5 + siLines.length * 4.5 + 4;

  // --- Section 5: Maladaptive Behaviors ---
  y = addSectionTitle(doc, "Section 5: Maladaptive Behaviors Targeted for Reduction", y + 2);
  if (behaviors.length > 0) {
    const bRows = behaviors.map((b) => [b.behavior || "—", b.topography || "—", b.frequency || "—", b.intensity || "—", b.duration || "—"]);
    autoTable(doc, {
      head: [["Behavior", "Topography", "Frequency", "Intensity", "Duration"]],
      body: bRows,
      startY: y,
      theme: "grid",
      styles: { fontSize: 7, cellPadding: 2 },
      headStyles: { fillColor: [220, 38, 38], textColor: 255, fontStyle: "bold" },
      margin: { left: 14, right: 14 },
    });
    y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 6;
    y += 4;
  } else {
    doc.setFontSize(9);
    doc.setTextColor(107, 114, 128);
    doc.text("No maladaptive behaviors listed.", 14, y);
    y += 8;
  }

  // --- Section 6: BIP ---
  y = addSectionTitle(doc, "Section 6: Behavior Intervention Plan (BIP)", y + 2);
  if (plan.behavior_intervention_plan) {
    doc.setFontSize(9);
    doc.setTextColor(55, 65, 81);
    const bipLines = doc.splitTextToSize(plan.behavior_intervention_plan, pageWidth - 28);
    doc.text(bipLines, 14, y);
    y += bipLines.length * 4.5 + 4;
  } else {
    doc.setFontSize(9);
    doc.setTextColor(107, 114, 128);
    doc.text("No BIP specified.", 14, y);
    y += 8;
  }

  // --- Section 7: Skill Acquisition Goals ---
  y = addSectionTitle(doc, "Section 7: Skill Acquisition Goals", y + 2);
  if (goals.length > 0) {
    const gRows = goals.map((g) => [g.domain || "—", g.description || "—", g.measurement || "—", g.baseline || "—", g.target || "—", g.target_date || "—"]);
    autoTable(doc, {
      head: [["Domain", "Goal", "Measurement", "Baseline", "Target", "Target Date"]],
      body: gRows,
      startY: y,
      theme: "grid",
      styles: { fontSize: 7, cellPadding: 2 },
      headStyles: { fillColor: [5, 150, 105], textColor: 255, fontStyle: "bold" },
      margin: { left: 14, right: 14 },
      columnStyles: {
        1: { cellWidth: 40 },
      },
    });
    y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 6;
    y += 4;
  } else {
    doc.setFontSize(9);
    doc.setTextColor(107, 114, 128);
    doc.text("No skill acquisition goals listed.", 14, y);
    y += 8;
  }

  // --- Section 8: Assessment Outcomes ---
  y = addSectionTitle(doc, "Section 8: Assessment Outcomes", y + 2);
  if (assessment?.raw_scores && typeof assessment.raw_scores === "object") {
    const c = ((assessment.raw_scores as Record<string, unknown>)._computed as Record<string, unknown>) ?? {};
    const outcomeRows: string[][] = [];
    if (c.milestones) {
      const m = c.milestones as Record<string, unknown>;
      outcomeRows.push(["Milestones", `${m.overallTotal ?? "—"} / ${m.maxOverall ?? 170}`, `${m.maxOverall ? Math.round((Number(m.overallTotal) / Number(m.maxOverall)) * 100) : 0}%`]);
    }
    if (c.barriers) {
      const b = c.barriers as Record<string, unknown>;
      outcomeRows.push(["Barriers", `${b.total ?? "—"} / ${b.max ?? 96}`, ""]);
    }
    if (c.transition) {
      const t = c.transition as Record<string, unknown>;
      outcomeRows.push(["Transition", `${t.total ?? "—"} / ${t.max ?? 36}`, ""]);
    }
    if (c.eesa) {
      const e = c.eesa as Record<string, unknown>;
      outcomeRows.push(["EESA", `${e.overallTotal ?? "—"}`, ""]);
    }
    if (c.task_analysis) {
      const ta = c.task_analysis as Record<string, unknown>;
      outcomeRows.push(["Task Analysis", `${ta.overallPercentage ?? "—"}%`, ""]);
    }
    if (outcomeRows.length > 0) {
      autoTable(doc, {
        head: [["Measure", "Score", "Percentage"]],
        body: outcomeRows,
        startY: y,
        theme: "grid",
        styles: { fontSize: 8, cellPadding: 2 },
        headStyles: { fillColor: [79, 70, 229], textColor: 255, fontStyle: "bold" },
        margin: { left: 14, right: 14 },
      });
      y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 6;
      y += 4;
    }
  }
  if (plan.assessment_outcomes) {
    doc.setFontSize(9);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(55, 65, 81);
    doc.text("Clinical Interpretation:", 14, y);
    doc.setFont("helvetica", "normal");
    const aoLines = doc.splitTextToSize(plan.assessment_outcomes, pageWidth - 28);
    doc.text(aoLines, 14, y + 5);
    y += 5 + aoLines.length * 4.5 + 4;
  }

  // --- Section 9: Parent Training Goals ---
  y = addSectionTitle(doc, "Section 9: Parent Training Goals", y + 2);
  if (parentGoals.length > 0) {
    const pgRows = parentGoals.map((g) => [g.goal || "—", g.method || "—", g.frequency || "—"]);
    autoTable(doc, {
      head: [["Goal", "Method", "Frequency"]],
      body: pgRows,
      startY: y,
      theme: "grid",
      styles: { fontSize: 8, cellPadding: 2 },
      headStyles: { fillColor: [124, 58, 237], textColor: 255, fontStyle: "bold" },
      margin: { left: 14, right: 14 },
    });
    y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 6;
    y += 4;
  } else {
    doc.setFontSize(9);
    doc.setTextColor(107, 114, 128);
    doc.text("No parent training goals listed.", 14, y);
    y += 8;
  }

  // --- Section 10: Service Coordination ---
  y = addSectionTitle(doc, "Section 10: Service Coordination Goals", y + 2);
  if (coordGoals.length > 0) {
    const cgRows = coordGoals.map((g) => [g.provider || "—", g.goal || "—", g.method || "—"]);
    autoTable(doc, {
      head: [["Provider", "Goal", "Method"]],
      body: cgRows,
      startY: y,
      theme: "grid",
      styles: { fontSize: 8, cellPadding: 2 },
      headStyles: { fillColor: [14, 165, 233], textColor: 255, fontStyle: "bold" },
      margin: { left: 14, right: 14 },
    });
    y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 6;
    y += 4;
  } else {
    doc.setFontSize(9);
    doc.setTextColor(107, 114, 128);
    doc.text("No service coordination goals listed.", 14, y);
    y += 8;
  }

  // --- Section 11: Discharge Criteria ---
  y = addSectionTitle(doc, "Section 11: Discharge Criteria", y + 2);
  if (plan.discharge_criteria) {
    doc.setFontSize(9);
    doc.setTextColor(55, 65, 81);
    const dcLines = doc.splitTextToSize(plan.discharge_criteria, pageWidth - 28);
    doc.text(dcLines, 14, y);
    y += dcLines.length * 4.5 + 4;
  } else {
    doc.setFontSize(9);
    doc.setTextColor(107, 114, 128);
    doc.text("No discharge criteria specified.", 14, y);
    y += 8;
  }

  // --- Section 12: Requested Services & CPT Codes ---
  y = addSectionTitle(doc, "Section 12: Requested Services & CPT Codes", y + 2);
  if (services.length > 0) {
    const sRows = services.map((s) => [s.service_name || "—", s.cpt_code || "—", s.frequency || "—", s.duration || "—", s.hours_per_week != null ? String(s.hours_per_week) : "—"]);
    autoTable(doc, {
      head: [["Service", "CPT Code", "Frequency", "Duration", "Hours/Week"]],
      body: sRows,
      startY: y,
      theme: "grid",
      styles: { fontSize: 8, cellPadding: 2 },
      headStyles: { fillColor: [79, 70, 229], textColor: 255, fontStyle: "bold" },
      margin: { left: 14, right: 14 },
    });
    y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 6;
    y += 4;
  } else {
    doc.setFontSize(9);
    doc.setTextColor(107, 114, 128);
    doc.text("No services requested.", 14, y);
    y += 8;
  }

  // --- Section 13: Therapy Schedule ---
  y = addSectionTitle(doc, "Section 13: Therapy Schedule", y + 2);
  if (schedule.length > 0) {
    const schRows = schedule.map((s) => [s.day || "—", s.time || "—", s.location || "—", s.service_type || "—"]);
    autoTable(doc, {
      head: [["Day", "Time", "Location", "Service Type"]],
      body: schRows,
      startY: y,
      theme: "grid",
      styles: { fontSize: 8, cellPadding: 2 },
      headStyles: { fillColor: [5, 150, 105], textColor: 255, fontStyle: "bold" },
      margin: { left: 14, right: 14 },
    });
    y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 6;
    y += 10;
  } else {
    doc.setFontSize(9);
    doc.setTextColor(107, 114, 128);
    doc.text("No therapy schedule listed.", 14, y);
    y += 8;
  }

  // --- Signature Block ---
  y = addSectionTitle(doc, "Signatures", Math.max(y + 4, doc.internal.pageSize.height - 70));
  const sigY = y + 10;
  doc.setDrawColor(156, 163, 175);
  doc.setLineWidth(0.3);

  // BCBA signature
  doc.line(14, sigY + 12, 90, sigY + 12);
  doc.setFontSize(8);
  doc.setTextColor(107, 114, 128);
  doc.text("BCBA Signature", 14, sigY + 16);

  // Date
  doc.line(14, sigY + 12, 90, sigY + 12); // line already drawn
  doc.text("Date", 14, sigY + 22);

  // Parent/Guardian signature
  doc.line(110, sigY + 12, 195, sigY + 12);
  doc.text("Parent / Guardian Signature", 110, sigY + 16);
  doc.text("Date", 110, sigY + 22);

  // --- Page footers ---
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    addPageFooter(doc, i, totalPages);
  }

  return doc.output("arraybuffer");
}

