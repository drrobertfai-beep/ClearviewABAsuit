function fmtDate(d: string | null | undefined): string {
  if (!d) return "—";
  return new Date(d).toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });
}

function parseJson<T>(val: unknown, fallback: T): T {
  if (Array.isArray(val)) return val as T;
  if (typeof val === "object" && val !== null) return val as T;
  return fallback;
}

function addPageFooter(doc: jsPDF, pageNum: number, totalPages: number) {
  const str = `Page ${pageNum} of ${totalPages} | Generated by ClearView ABA Suite | ${new Date().toLocaleString()}`;
  doc.setFontSize(8);
  doc.setTextColor(128, 128, 128);
  doc.text(str, 14, doc.internal.pageSize.height - 10, {
    align: "left",
  });
}

function addHeader(doc: jsPDF, title: string) {
  doc.setFontSize(10);
  doc.setTextColor(79, 70, 229); // indigo-600
  doc.text("ClearView ABA Suite", 14, 12);
  doc.setFontSize(16);
  doc.setTextColor(17, 24, 39); // gray-900
  doc.text(title, 14, 22);
  doc.setDrawColor(79, 70, 229);
  doc.setLineWidth(0.5);
  doc.line(14, 26, doc.internal.pageSize.width - 14, 26);
}

function addSectionTitle(doc: jsPDF, title: string, y: number): number {
  doc.setFontSize(12);
  doc.setTextColor(79, 70, 229);
  doc.setFont("helvetica", "bold");
  doc.text(title, 14, y);
  doc.setDrawColor(209, 213, 219);
  doc.setLineWidth(0.3);
  doc.line(14, y + 2, doc.internal.pageSize.width - 14, y + 2);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(17, 24, 39);
  return y + 8;
}

/** Starts a new page when `needed` mm would not fit below `y`. */
function ensureSpace(doc: jsPDF, y: number, needed: number): number {
  const bottom = doc.internal.pageSize.height - 20;
  if (y + needed <= bottom) return y;
  doc.addPage();
  return 25;
}

/**
 * Pixel size of a PNG or JPEG, read from its header. Needed because jsPDF wants
 * a width and height up front and the server has no DOM to measure with.
 */
function imagePixelSize(
  bytes: Uint8Array,
): { width: number; height: number } | null {
  // PNG: IHDR width/height are the 4-byte big-endian values at 16 and 20.
  if (
    bytes.length > 24 &&
    bytes[0] === 0x89 &&
    bytes[1] === 0x50 &&
    bytes[2] === 0x4e &&
    bytes[3] === 0x47
  ) {
    const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.length);
    return { width: view.getUint32(16), height: view.getUint32(20) };
  }
  // JPEG: walk the segments to a start-of-frame marker.
  if (bytes.length > 4 && bytes[0] === 0xff && bytes[1] === 0xd8) {
    let i = 2;
    while (i + 9 < bytes.length) {
      if (bytes[i] !== 0xff) {
        i += 1;
        continue;
      }
      const marker = bytes[i + 1];
      const isSof =
        (marker >= 0xc0 && marker <= 0xc3) ||
        (marker >= 0xc5 && marker <= 0xc7) ||
        (marker >= 0xc9 && marker <= 0xcb) ||
        (marker >= 0xcd && marker <= 0xcf);
      if (isSof) {
        const height = (bytes[i + 5] << 8) | bytes[i + 6];
        const width = (bytes[i + 7] << 8) | bytes[i + 8];
        if (width > 0 && height > 0) return { width, height };
        return null;
      }
      const length = (bytes[i + 2] << 8) | bytes[i + 3];
      if (length <= 0) return null;
      i += 2 + length;
    }
  }
  return null;
}

/** The base64 payload of an attachment as bytes. */
function attachmentBytes(attachment: PlanAttachmentBytes): Uint8Array {
  return new Uint8Array(Buffer.from(attachment.data_base64, "base64"));
}

