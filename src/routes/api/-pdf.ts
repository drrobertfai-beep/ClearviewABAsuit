function buildAssessmentPDF(assessment: Assessment, client: Client | null): Uint8Array {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const today = fmtDate(new Date().toISOString());
  const pageWidth = doc.internal.pageSize.width;
  let y = 30;

  // --- Header ---
  addHeader(doc, "VB-MAPP Assessment Report");
  y = 32;
  doc.setFontSize(9);
  doc.setTextColor(75, 85, 99);
  doc.text(`Date Generated: ${today}`, 14, y); y += 5;

  // --- Client Info ---
  y = addSectionTitle(doc, "Client Information", y + 3);
  const clientInfo = [
    ["Client Name", client?.name ?? "—"],
    ["Date of Birth", client?.date_of_birth ? fmtDate(client.date_of_birth) : "—"],
    ["Assessment Date", fmtDate(assessment.assessment_date)],
    ["Assessor", assessment.assessor_name || "—"],
    ["Tool", `${assessment.tool_name}${assessment.tool_version ? ` v${assessment.tool_version}` : ""}`],
    ["Status", assessment.status],
  ];
  for (const [label, val] of clientInfo) {
    doc.setFontSize(9);
    doc.setTextColor(55, 65, 81);
    doc.setFont("helvetica", "bold");
    doc.text(`${label}:`, 14, y);
    doc.setFont("helvetica", "normal");
    doc.text(val, 55, y);
    y += 5;
  }

  // --- Scores ---
  const raw = assessment.raw_scores as Record<string, unknown> | null;
  const computed = raw?._computed as Record<string, unknown> | undefined;

  if (computed) {
    y += 4;

    // Milestones table
    y = addSectionTitle(doc, "Milestones Assessment", y);
    const ms = computed.milestones as Record<string, unknown> | undefined;
    if (ms?.domainTotals) {
      const dt = ms.domainTotals as Record<string, Record<string, number>>;
      const lt = ms.levelTotals as Record<string, number> | undefined;
      const rows: string[][] = [];
      const levels = ["level1", "level2", "level3"];
      const levelNames: Record<string, string> = { level1: "Level 1 (0-18mo)", level2: "Level 2 (18-30mo)", level3: "Level 3 (30-48mo)" };

      for (const lvl of levels) {
        const domains = dt[lvl];
        if (!domains) continue;
        for (const [domainKey, total] of Object.entries(domains)) {
          const domainDef = VB_MAPP_MILESTONES[lvl as keyof typeof VB_MAPP_MILESTONES]?.[domainKey as keyof (typeof VB_MAPP_MILESTONES)[keyof typeof VB_MAPP_MILESTONES]];
          const domainName = (domainDef as { name?: string })?.name ?? domainKey;
          const maxScore = (domainDef as { items?: string[] })?.items?.length ?? 5;
          const pct = maxScore > 0 ? Math.round((total / maxScore) * 100) : 0;
          rows.push([levelNames[lvl] ?? lvl, domainName, String(total), String(maxScore), `${pct}%`]);
        }
        if (lt?.[lvl] !== undefined) {
          const maxForLevel = Object.values(dt[lvl] ?? {}).reduce((a: number, t: number) => a + (typeof t === "number" ? t : 0), 0);
          rows.push(["", `${levelNames[lvl]} Total`, String(lt[lvl]), "", ""]);
        }
      }

      autoTable(doc, {
        head: [["Level", "Domain", "Score", "Max", "%"]],
        body: rows,
        startY: y,
        theme: "grid",
        styles: { fontSize: 8, cellPadding: 2 },
        headStyles: { fillColor: [79, 70, 229], textColor: 255, fontStyle: "bold" },
        margin: { left: 14, right: 14 },
      });
      y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 10;
      y += 4;
    }

    // Barriers table
    y = addSectionTitle(doc, "Barriers Assessment", y + 2);
    const barriers = raw?.barriers as Record<string, number> | undefined;
    const barriersComputed = computed.barriers as Record<string, number> | undefined;
    if (barriers) {
      const bRows = VB_MAPP_BARRIERS.map((b) => {
        const score = barriers[b.key] ?? 0;
        const severity = score >= 3 ? "Severe" : score >= 2 ? "Moderate" : score >= 1 ? "Mild" : "None";
        return [b.name, String(score), severity];
      });
      if (barriersComputed) {
        bRows.push(["TOTAL", String(barriersComputed.total ?? 0), `Max: ${barriersComputed.max ?? 96}`]);
      }

      autoTable(doc, {
        head: [["Barrier", "Score (0-4)", "Severity"]],
        body: bRows,
        startY: y,
        theme: "grid",
        styles: { fontSize: 8, cellPadding: 2 },
        headStyles: { fillColor: [220, 38, 38], textColor: 255, fontStyle: "bold" },
        margin: { left: 14, right: 14 },
      });
      y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 10;
      y += 4;
    }

    // Transition table
    y = addSectionTitle(doc, "Transition Assessment", y + 2);
    const transition = raw?.transition as Record<string, number> | undefined;
    const transComputed = computed.transition as Record<string, number> | undefined;
    if (transition) {
      const tRows = VB_MAPP_TRANSITION.map((t) => {
        const score = transition[t.key] ?? 0;
        const rating = score === 2 ? "Fully Ready" : score === 1 ? "Emerging" : "Not Ready";
        return [t.name, String(score), rating];
      });
      if (transComputed) {
        tRows.push(["TOTAL", String(transComputed.total ?? 0), `Max: ${transComputed.max ?? 36}`]);
      }

      autoTable(doc, {
        head: [["Transition Item", "Score (0-2)", "Rating"]],
        body: tRows,
        startY: y,
        theme: "grid",
        styles: { fontSize: 8, cellPadding: 2 },
        headStyles: { fillColor: [5, 150, 105], textColor: 255, fontStyle: "bold" },
        margin: { left: 14, right: 14 },
      });
      y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 10;
      y += 4;
    }

    // EESA Scores
    y = addSectionTitle(doc, "EESA (Early Echoic Skills Assessment)", y + 2);
    const eesa = raw?.eesa as Record<string, number[]> | undefined;
    const eesaComputed = computed.eesa as Record<string, unknown> | undefined;
    if (eesa) {
      const eRows = VB_MAPP_EESA_GROUPS.map((g) => {
        const scores = eesa[g.key] ?? [];
        const total = scores.reduce((a, v) => a + v, 0);
        const max = g.targets.length;
        return [g.name, String(total), String(max), `${max > 0 ? Math.round((total / max) * 100) : 0}%`];
      });
      if (eesaComputed?.overallTotal !== undefined) {
        eRows.push(["TOTAL", String(eesaComputed.overallTotal), "", ""]);
      }

      autoTable(doc, {
        head: [["Group", "Score", "Max", "%"]],
        body: eRows,
        startY: y,
        theme: "grid",
        styles: { fontSize: 8, cellPadding: 2 },
        headStyles: { fillColor: [124, 58, 237], textColor: 255, fontStyle: "bold" },
        margin: { left: 14, right: 14 },
      });
      y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 10;
      y += 4;
    }

    // Task Analysis
    y = addSectionTitle(doc, "Task Analysis — Domain Completion", y + 2);
    const ta = raw?.task_analysis as Record<string, number[]> | undefined;
    const taComputed = computed.task_analysis as Record<string, unknown> | undefined;
    if (ta) {
      const taRows = VB_MAPP_TASK_ANALYSIS_DOMAINS.map((d) => {
        const scores = ta[d.key] ?? [];
        const completed = scores.filter((v) => v === 1).length;
        const total = d.skills.length;
        const pct = total > 0 ? Math.round((completed / total) * 100) : 0;
        return [d.name, `${completed}/${total}`, `${pct}%`];
      });
      if (taComputed?.overallPercentage !== undefined) {
        taRows.push(["OVERALL", `${taComputed.totalCompleted ?? 0}/${taComputed.totalItems ?? 0}`, `${taComputed.overallPercentage}%`]);
      }

      autoTable(doc, {
        head: [["Domain", "Completed", "Percentage"]],
        body: taRows,
        startY: y,
        theme: "grid",
        styles: { fontSize: 8, cellPadding: 2 },
        headStyles: { fillColor: [14, 165, 233], textColor: 255, fontStyle: "bold" },
        margin: { left: 14, right: 14 },
      });
      y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 10;
      y += 4;
    }
  }

  // Summary Notes
  if (assessment.summary_notes) {
    y = addSectionTitle(doc, "Summary & Clinical Notes", y + 4);
    doc.setFontSize(9);
    doc.setTextColor(55, 65, 81);
    const lines = doc.splitTextToSize(assessment.summary_notes, pageWidth - 28);
    doc.text(lines, 14, y);
    y += lines.length * 4.5 + 6;
  }

  // --- Page footers ---
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    addPageFooter(doc, i, totalPages);
  }

  return doc.output("arraybuffer");
}

