/** "home" -> "Home"; anything unknown is echoed as-is. */
function settingLabel(value: string): string {
  if (!value) return "—";
  return value.charAt(0).toUpperCase() + value.slice(1);
}

/** "January 1, 2026 – June 30, 2026", or an em dash when unset. */
function authorizationPeriodLabel(plan: TreatmentPlan): string {
  if (!plan.authorization_start_date && !plan.authorization_end_date) return "—";
  return `${formatDateOnly(plan.authorization_start_date)} – ${formatDateOnly(plan.authorization_end_date)}`;
}

