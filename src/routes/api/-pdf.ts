function buildTreatmentPlanPDF(
  plan: TreatmentPlan,
  client: Client | null,
  assessment: Assessment | null,
  priorPlan: TreatmentPlan | null = null,
  attachments: PlanAttachmentBytes[] = [],
): Uint8Array {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const today = fmtDate(new Date().toISOString());
  const pageWidth = doc.internal.pageSize.width;
  let y = 30;

  const concurrent = parseJson<{ service: string; provider: string; frequency?: string }[]>(plan.concurrent_services, []);
  const behaviors = parseJson<{ behavior: string; topography: string; frequency: string; intensity: string; duration: string }[]>(plan.maladaptive_behaviors, []);
  // Reauthorization: one progress record per carried-forward goal, keyed by the
  // goal's stable id. Empty on a first authorization.
  const goalProgress = normalizeGoalProgress(plan.goal_progress);
  const goals = parseJson<{ id?: string; domain: string; description: string; measurement: string; baseline: string; target: string; target_date: string }[]>(plan.skill_acquisition_goals, []).filter((g) => {
    // A goal dropped from the new request is listed, with its reason, in the
    // reauthorization section instead of here.
    const record = g.id ? progressFor(goalProgress, g.id) : undefined;
    return !record?.dropped;
  });
  const parentGoals = parseJson<{ goal: string; method: string; frequency: string }[]>(plan.parent_training_goals, []);
  const coordGoals = parseJson<{ provider: string; goal: string; method: string }[]>(plan.service_coordination_goals, []);
  // Read through the normalizers: plans saved before the authorization fields
  // existed still hold the legacy jsonb shapes and must render identically.
  const services = normalizeServiceLines(plan.requested_services);
  const schedule = sortSchedule(normalizeSchedule(plan.therapy_schedule));
  const totalRequestedHours = totalHoursPerWeek(services);
  const totalScheduledHours = scheduledHoursPerWeek(schedule);

  // --- Cover Page ---
  addHeader(doc, "ClearView ABA Suite");
  // Centered cover content
  const centerX = pageWidth / 2;
  doc.setFontSize(22);
  doc.setTextColor(17, 24, 39);
  doc.setFont("helvetica", "bold");
  doc.text("Individualized Treatment Plan", centerX, 80, { align: "center" });

  doc.setFontSize(14);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(55, 65, 81);
  doc.text(`Prepared for: ${client?.name ?? "—"}`, centerX, 100, { align: "center" });

  doc.setFontSize(10);
  doc.setTextColor(107, 114, 128);
  const coverInfo = [
    `Date: ${today}`,
    `BCBA: ${assessment?.assessor_name ?? "—"}`,
    `Plan Status: ${plan.status}`,
    `Authorization Period: ${authorizationPeriodLabel(plan)}`,
    `Authorization Number: ${plan.authorization_number || "Not yet assigned"}`,
    `Requested Hours/Week: ${totalRequestedHours}`,
    `Generated by ClearView ABA Suite`,
  ];
  let cy = 115;
  for (const line of coverInfo) {
    doc.text(line, centerX, cy, { align: "center" });
    cy += 6;
  }

  // --- Section 1: Client Identification ---
  doc.addPage();
  y = 30;
  addHeader(doc, "Treatment Plan — Detail");
  y = 32;
  doc.setFontSize(9);
  doc.setTextColor(75, 85, 99);
  doc.text(`Date Generated: ${today}`, 14, y);

  y = addSectionTitle(doc, "Section 1: Client Identification & Background", y + 5);
  const ident: [string, string][] = [
    ["Client Name", client?.name ?? "—"],
    ["Date of Birth", client?.date_of_birth ? fmtDate(client.date_of_birth) : "—"],
    ["Gender", client?.gender ?? "—"],
    ["Contact", client?.contact_email ?? client?.contact_phone ?? "—"],
    ["Address", client?.address ?? "—"],
    ["Referral Source", client?.referral_source ?? "—"],
    ["Reason for Referral", plan.reason_for_referral ?? "—"],
  ];
  for (const [l, v] of ident) {
    doc.setFontSize(9);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(55, 65, 81);
    doc.text(`${l}:`, 14, y);
    doc.setFont("helvetica", "normal");
    doc.text(v, 55, y);
    y += 5;
  }

  // --- Section 2: Diagnosis & Treatment History ---
  y = addSectionTitle(doc, "Section 2: Diagnosis & Treatment History", y + 3);
  doc.setFontSize(9);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(55, 65, 81);
  doc.text("Diagnosis:", 14, y);
  doc.setFont("helvetica", "normal");
  doc.text(plan.diagnosis || "—", 48, y, { maxWidth: pageWidth - 62 });
  y += 6;

  doc.setFont("helvetica", "bold");
  doc.text("Treatment History:", 14, y);
  doc.setFont("helvetica", "normal");
  const thLines = doc.splitTextToSize(plan.treatment_history || "—", pageWidth - 28);
  doc.text(thLines, 14, y + 5);
  y += 5 + thLines.length * 4.5 + 4;

  // --- Section 3: Concurrent Services ---
  y = addSectionTitle(doc, "Section 3: Concurrent Services", y + 2);
  if (concurrent.length > 0) {
    const cRows = concurrent.map((c) => [c.service || "—", c.provider || "—", c.frequency || "—"]);
    autoTable(doc, {
      head: [["Service", "Provider", "Frequency"]],
      body: cRows,
      startY: y,
      theme: "grid",
      styles: { fontSize: 8, cellPadding: 2 },
      headStyles: { fillColor: [79, 70, 229], textColor: 255, fontStyle: "bold" },
      margin: { left: 14, right: 14 },
    });
    y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 6;
    y += 4;
  } else {
    doc.setFontSize(9);
    doc.setTextColor(107, 114, 128);
    doc.text("No concurrent services listed.", 14, y);
    y += 8;
  }

  // --- Section 4: Family & School ---
  y = addSectionTitle(doc, "Section 4: Family & School Information", y + 2);
  doc.setFontSize(9);
  doc.setFont("helvetica", "bold");
  doc.text("Family History:", 14, y);
  doc.setFont("helvetica", "normal");
  const fhLines = doc.splitTextToSize(plan.family_history || "—", pageWidth - 28);
  doc.text(fhLines, 14, y + 5);
  y += 5 + fhLines.length * 4.5 + 4;

  doc.setFont("helvetica", "bold");
  doc.text("School Information:", 14, y);
  doc.setFont("helvetica", "normal");
  const siLines = doc.splitTextToSize(plan.school_info || "—", pageWidth - 28);
  doc.text(siLines, 14, y + 5);
  y += 5 + siLines.length * 4.5 + 4;

  // --- Section 5: Maladaptive Behaviors ---
  y = addSectionTitle(doc, "Section 5: Maladaptive Behaviors Targeted for Reduction", y + 2);
  if (behaviors.length > 0) {
    const bRows = behaviors.map((b) => [b.behavior || "—", b.topography || "—", b.frequency || "—", b.intensity || "—", b.duration || "—"]);
    autoTable(doc, {
      head: [["Behavior", "Topography", "Frequency", "Intensity", "Duration"]],
      body: bRows,
      startY: y,
      theme: "grid",
      styles: { fontSize: 7, cellPadding: 2 },
      headStyles: { fillColor: [220, 38, 38], textColor: 255, fontStyle: "bold" },
      margin: { left: 14, right: 14 },
    });
    y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 6;
    y += 4;
  } else {
    doc.setFontSize(9);
    doc.setTextColor(107, 114, 128);
    doc.text("No maladaptive behaviors listed.", 14, y);
    y += 8;
  }

  // --- Section 6: BIP ---
  y = addSectionTitle(doc, "Section 6: Behavior Intervention Plan (BIP)", y + 2);
  if (plan.behavior_intervention_plan) {
    doc.setFontSize(9);
    doc.setTextColor(55, 65, 81);
    const bipLines = doc.splitTextToSize(plan.behavior_intervention_plan, pageWidth - 28);
    doc.text(bipLines, 14, y);
    y += bipLines.length * 4.5 + 4;
  } else {
    doc.setFontSize(9);
    doc.setTextColor(107, 114, 128);
    doc.text("No BIP specified.", 14, y);
    y += 8;
  }

  // --- Section 7: Skill Acquisition Goals ---
  y = addSectionTitle(doc, "Section 7: Skill Acquisition Goals", y + 2);
  if (goals.length > 0) {
    const gRows = goals.map((g) => [g.domain || "—", g.description || "—", g.measurement || "—", g.baseline || "—", g.target || "—", g.target_date || "—"]);
    autoTable(doc, {
      head: [["Domain", "Goal", "Measurement", "Baseline", "Target", "Target Date"]],
      body: gRows,
      startY: y,
      theme: "grid",
      styles: { fontSize: 7, cellPadding: 2 },
      headStyles: { fillColor: [5, 150, 105], textColor: 255, fontStyle: "bold" },
      margin: { left: 14, right: 14 },
      columnStyles: {
        1: { cellWidth: 40 },
      },
    });
    y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 6;
    y += 4;
  } else {
    doc.setFontSize(9);
    doc.setTextColor(107, 114, 128);
    doc.text("No skill acquisition goals listed.", 14, y);
    y += 8;
  }

  // --- Section 8: Assessment Outcomes ---
  y = addSectionTitle(doc, "Section 8: Assessment Outcomes", y + 2);
  if (assessment?.raw_scores && typeof assessment.raw_scores === "object") {
    const c = ((assessment.raw_scores as Record<string, unknown>)._computed as Record<string, unknown>) ?? {};
    const outcomeRows: string[][] = [];
    if (c.milestones) {
      const m = c.milestones as Record<string, unknown>;
      outcomeRows.push(["Milestones", `${m.overallTotal ?? "—"} / ${m.maxOverall ?? 170}`, `${m.maxOverall ? Math.round((Number(m.overallTotal) / Number(m.maxOverall)) * 100) : 0}%`]);
    }
    if (c.barriers) {
      const b = c.barriers as Record<string, unknown>;
      outcomeRows.push(["Barriers", `${b.total ?? "—"} / ${b.max ?? 96}`, ""]);
    }
    if (c.transition) {
      const t = c.transition as Record<string, unknown>;
      outcomeRows.push(["Transition", `${t.total ?? "—"} / ${t.max ?? 36}`, ""]);
    }
    if (c.eesa) {
      const e = c.eesa as Record<string, unknown>;
      outcomeRows.push(["EESA", `${e.overallTotal ?? "—"}`, ""]);
    }
    if (c.task_analysis) {
      const ta = c.task_analysis as Record<string, unknown>;
      outcomeRows.push(["Task Analysis", `${ta.overallPercentage ?? "—"}%`, ""]);
    }
    if (outcomeRows.length > 0) {
      autoTable(doc, {
        head: [["Measure", "Score", "Percentage"]],
        body: outcomeRows,
        startY: y,
        theme: "grid",
        styles: { fontSize: 8, cellPadding: 2 },
        headStyles: { fillColor: [79, 70, 229], textColor: 255, fontStyle: "bold" },
        margin: { left: 14, right: 14 },
      });
      y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 6;
      y += 4;
    }
  }
  if (plan.assessment_outcomes) {
    doc.setFontSize(9);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(55, 65, 81);
    doc.text("Clinical Interpretation:", 14, y);
    doc.setFont("helvetica", "normal");
    const aoLines = doc.splitTextToSize(plan.assessment_outcomes, pageWidth - 28);
    doc.text(aoLines, 14, y + 5);
    y += 5 + aoLines.length * 4.5 + 4;
  }

  // --- Section 9: Parent Training Goals ---
  y = addSectionTitle(doc, "Section 9: Parent Training Goals", y + 2);
  if (parentGoals.length > 0) {
    const pgRows = parentGoals.map((g) => [g.goal || "—", g.method || "—", g.frequency || "—"]);
    autoTable(doc, {
      head: [["Goal", "Method", "Frequency"]],
      body: pgRows,
      startY: y,
      theme: "grid",
      styles: { fontSize: 8, cellPadding: 2 },
      headStyles: { fillColor: [124, 58, 237], textColor: 255, fontStyle: "bold" },
      margin: { left: 14, right: 14 },
    });
    y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 6;
    y += 4;
  } else {
    doc.setFontSize(9);
    doc.setTextColor(107, 114, 128);
    doc.text("No parent training goals listed.", 14, y);
    y += 8;
  }

  // --- Section 10: Service Coordination ---
  y = addSectionTitle(doc, "Section 10: Service Coordination Goals", y + 2);
  if (coordGoals.length > 0) {
    const cgRows = coordGoals.map((g) => [g.provider || "—", g.goal || "—", g.method || "—"]);
    autoTable(doc, {
      head: [["Provider", "Goal", "Method"]],
      body: cgRows,
      startY: y,
      theme: "grid",
      styles: { fontSize: 8, cellPadding: 2 },
      headStyles: { fillColor: [14, 165, 233], textColor: 255, fontStyle: "bold" },
      margin: { left: 14, right: 14 },
    });
    y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 6;
    y += 4;
  } else {
    doc.setFontSize(9);
    doc.setTextColor(107, 114, 128);
    doc.text("No service coordination goals listed.", 14, y);
    y += 8;
  }

  // --- Section 11: Discharge Criteria ---
  y = addSectionTitle(doc, "Section 11: Discharge Criteria", y + 2);
  if (plan.discharge_criteria) {
    doc.setFontSize(9);
    doc.setTextColor(55, 65, 81);
    const dcLines = doc.splitTextToSize(plan.discharge_criteria, pageWidth - 28);
    doc.text(dcLines, 14, y);
    y += dcLines.length * 4.5 + 4;
  } else {
    doc.setFontSize(9);
    doc.setTextColor(107, 114, 128);
    doc.text("No discharge criteria specified.", 14, y);
    y += 8;
  }

  // --- Section 12: Requested Services & CPT Codes ---
  y = ensureSpace(doc, y, 45);
  y = addSectionTitle(doc, "Section 12: Requested Services & CPT Codes", y + 2);
  if (services.length > 0) {
    const sRows = services.map((s) => [
      s.cpt_code || "—",
      s.service_name || "—",
      s.hours_per_week != null ? String(s.hours_per_week) : "—",
      s.session_duration_minutes != null
        ? formatDuration(s.session_duration_minutes)
        : "—",
      settingLabel(s.setting),
      s.provider_type || "—",
    ]);
    autoTable(doc, {
      head: [["CPT Code", "Service Description", "Hours/Week", "Session Duration", "Setting", "Provider"]],
      body: sRows,
      foot: [
        [
          {
            content: "Total requested hours per week",
            colSpan: 3,
            styles: { halign: "right", fontStyle: "bold" },
          },
          {
            content: `${totalRequestedHours} hrs/wk`,
            colSpan: 3,
            styles: { fontStyle: "bold", textColor: [79, 70, 229] },
          },
        ],
      ],
      startY: y,
      theme: "grid",
      styles: { fontSize: 8, cellPadding: 2 },
      headStyles: { fillColor: [79, 70, 229], textColor: 255, fontStyle: "bold" },
      footStyles: { fillColor: [238, 242, 255], textColor: [30, 27, 75] },
      columnStyles: {
        1: { cellWidth: 52 },
      },
      margin: { left: 14, right: 14 },
    });
    y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 6;
    y += 6;
  } else {
    doc.setFontSize(9);
    doc.setTextColor(107, 114, 128);
    doc.text("No services requested.", 14, y);
    y += 8;
  }

  // --- Section 13: Therapy Schedule ---
  y = ensureSpace(doc, y, 45);
  y = addSectionTitle(doc, "Section 13: Weekly Therapy Schedule", y + 2);
  if (schedule.length > 0) {
    const schRows = schedule.map((s) => [
      s.day || "—",
      s.start_time || "—",
      s.end_time || "—",
      formatDuration(scheduleDurationMinutes(s)),
      s.service || "—",
      settingLabel(s.setting),
      s.provider || "—",
    ]);
    autoTable(doc, {
      head: [["Day", "Start", "End", "Duration", "Service", "Setting", "Provider"]],
      body: schRows,
      foot: [
        [
          {
            content: "Total scheduled hours per week",
            colSpan: 4,
            styles: { halign: "right", fontStyle: "bold" },
          },
          {
            content: `${totalScheduledHours} hrs/wk`,
            colSpan: 3,
            styles: { fontStyle: "bold", textColor: [4, 120, 87] },
          },
        ],
      ],
      startY: y,
      theme: "grid",
      styles: { fontSize: 8, cellPadding: 2 },
      headStyles: { fillColor: [5, 150, 105], textColor: 255, fontStyle: "bold" },
      footStyles: { fillColor: [236, 253, 245], textColor: [6, 78, 59] },
      margin: { left: 14, right: 14 },
    });
    y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 6;
    y += 6;
  } else {
    doc.setFontSize(9);
    doc.setTextColor(107, 114, 128);
    doc.text("No therapy schedule listed.", 14, y);
    y += 8;
  }

  // --- Section 14: Titration Plan ---
  // Phased step-down of the authorized hours. Plans written before titration
  // existed export the empty line instead of an error.
  const titrationPhases = normalizeTitrationPhases(plan.titration_phases);
  y = ensureSpace(doc, y, 45);
  y = addSectionTitle(doc, "Section 14: Titration Plan", y + 2);
  if (titrationPhases.length === 0) {
    doc.setFontSize(9);
    doc.setTextColor(107, 114, 128);
    doc.text("No titration plan recorded.", 14, y);
    y += 8;
  } else {
    if (plan.titration_rationale) {
      doc.setFontSize(9);
      doc.setTextColor(55, 65, 81);
      const rationaleLines = doc.splitTextToSize(
        plan.titration_rationale,
        pageWidth - 28,
      ) as string[];
      let remaining = rationaleLines;
      while (remaining.length > 0) {
        const pageBottom = doc.internal.pageSize.height - 20;
        const capacity = Math.floor((pageBottom - y) / 4.5);
        if (capacity <= 0) {
          doc.addPage();
          y = 25;
          continue;
        }
        const chunk = remaining.slice(0, capacity);
        doc.text(chunk, 14, y);
        y += chunk.length * 4.5;
        remaining = remaining.slice(capacity);
        if (remaining.length > 0) {
          doc.addPage();
          y = 25;
        }
      }
      y += 4;
    }

    autoTable(doc, {
      head: [["Phase", "Weeks", "Hours / week by CPT", "Total"]],
      body: titrationPhases.map((phase) => [
        phase.label || "—",
        phaseWeekLabel(phase),
        phase.lines.length === 0
          ? "—"
          : phase.lines
              .map((line) => `${line.cpt_code || "—"}: ${line.hours_per_week ?? "—"}`)
              .join("\n"),
        `${phaseHours(phase)} hrs/wk`,
      ]),
      startY: y,
      theme: "grid",
      // Long CPT lists wrap inside the cell instead of overflowing the page.
      styles: { fontSize: 8, cellPadding: 2, valign: "top", overflow: "linebreak" },
      headStyles: { fillColor: [79, 70, 229], textColor: 255, fontStyle: "bold" },
      columnStyles: {
        0: { cellWidth: 36 },
        1: { cellWidth: 26 },
        2: { cellWidth: 72 },
        3: { cellWidth: 26, fontStyle: "bold" },
      },
      // A phase row is never split across two pages.
      rowPageBreak: "avoid",
      margin: { left: 14, right: 14 },
    });
    y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 6;
    y += 5;

    // Criteria, one labelled block per phase, each line page-guarded so long
    // BCBA prose wraps and paginates without overflowing.
    const printBlock = (heading: string, text: string) => {
      doc.setFont("helvetica", "bold");
      doc.setFontSize(8.5);
      doc.setTextColor(55, 65, 81);
      y = ensureSpace(doc, y, 12);
      doc.text(heading, 14, y);
      y += 4.5;
      doc.setFont("helvetica", "normal");
      doc.setTextColor(75, 85, 99);
      const lines = doc.splitTextToSize(text || "—", pageWidth - 28) as string[];
      for (const line of lines) {
        y = ensureSpace(doc, y, 5);
        doc.text(line, 14, y);
        y += 4.2;
      }
      y += 2.5;
    };
    for (const phase of titrationPhases) {
      printBlock(
        `${phase.label || "Phase"} (${phaseWeekLabel(phase)}) — criteria to step down:`,
        phase.criteria_to_step_down,
      );
      printBlock(
        `${phase.label || "Phase"} — criteria to step back up:`,
        phase.criteria_to_step_up,
      );
    }
    y += 2;
  }

  // --- Section 15: Authorization Period & Clinical Justification ---
  y = ensureSpace(doc, y, 60);
  y = addSectionTitle(doc, "Section 15: Authorization Request & Medical Necessity", y + 2);
  doc.setFontSize(9);
  const authRows: [string, string][] = [
    ["Authorization Period", authorizationPeriodLabel(plan)],
    ["Authorization Number", plan.authorization_number || "Not yet assigned"],
    ["Total Requested Hours/Week", `${totalRequestedHours} hours`],
    ["Total Scheduled Hours/Week", `${totalScheduledHours} hours`],
  ];
  for (const [label, value] of authRows) {
    doc.setFont("helvetica", "bold");
    doc.setTextColor(55, 65, 81);
    doc.text(`${label}:`, 14, y);
    doc.setFont("helvetica", "normal");
    doc.text(value, 70, y);
    y += 5;
  }
  y += 3;

  doc.setFont("helvetica", "bold");
  doc.setTextColor(55, 65, 81);
  doc.text("Clinical Justification / Medical Necessity:", 14, y);
  y += 5;
  doc.setFont("helvetica", "normal");
  if (plan.clinical_justification) {
    const cjLines = doc.splitTextToSize(plan.clinical_justification, pageWidth - 28) as string[];
    const lineHeight = 4.5;
    let remaining = cjLines;
    while (remaining.length > 0) {
      const pageBottom = doc.internal.pageSize.height - 20;
      const capacity = Math.floor((pageBottom - y) / lineHeight);
      if (capacity <= 0) {
        doc.addPage();
        y = 25;
        continue;
      }
      const chunk = remaining.slice(0, capacity);
      doc.text(chunk, 14, y);
      y += chunk.length * lineHeight;
      remaining = remaining.slice(capacity);
      if (remaining.length > 0) {
        doc.addPage();
        y = 25;
      }
    }
    y += 4;
  } else {
    doc.setTextColor(107, 114, 128);
    doc.text("No clinical justification recorded.", 14, y);
    y += 8;
  }

  // --- Section 16: Reauthorization Progress ---
  // Only a reauthorization has a prior plan; a first authorization exports
  // exactly as it did before this section existed.
  if (plan.prior_plan_id) {
    y = ensureSpace(doc, y, 60);
    y = addSectionTitle(doc, "Section 16: Reauthorization Progress", y + 2);

    const priorHours = priorPlan
      ? totalHoursPerWeek(normalizeServiceLines(priorPlan.requested_services))
      : 0;
    const priorRows: [string, string][] = [
      [
        "Reauthorization of",
        priorPlan ? fmtDate(priorPlan.created_at) : "A prior plan",
      ],
      [
        "Prior authorization number",
        priorPlan?.authorization_number || "Not recorded",
      ],
      [
        "Prior authorization period",
        priorPlan ? authorizationPeriodLabel(priorPlan) : "—",
      ],
      [
        "Hours per week",
        `Prior ${priorHours} → this request ${totalRequestedHours}`,
      ],
    ];
    for (const [label, value] of priorRows) {
      doc.setFont("helvetica", "bold");
      doc.setFontSize(9);
      doc.setTextColor(55, 65, 81);
      doc.text(`${label}:`, 14, y);
      doc.setFont("helvetica", "normal");
      doc.text(value, 70, y);
      y += 5;
    }
    y += 2;

    if (plan.hours_increase_justification) {
      doc.setFont("helvetica", "bold");
      doc.setTextColor(55, 65, 81);
      doc.text("Justification for the increase in hours:", 14, y);
      y += 5;
      doc.setFont("helvetica", "normal");
      doc.setTextColor(75, 85, 99);
      const justLines = doc.splitTextToSize(
        plan.hours_increase_justification,
        pageWidth - 28,
      ) as string[];
      for (const line of justLines) {
        y = ensureSpace(doc, y, 5);
        doc.text(line, 14, y);
        y += 4.2;
      }
      y += 3;
    }

    const progressRows = goals
      .map((g) => ({ goal: g, record: g.id ? progressFor(goalProgress, g.id) : undefined }))
      .filter((row) => row.record && !row.record.dropped)
      .map((row) => [
        `${row.goal.domain || "—"}: ${row.goal.description || "—"}`,
        row.record!.baseline || row.goal.baseline || "—",
        row.record!.current || "—",
        row.goal.measurement || "—",
        goalProgressStatusLabel(row.record!.status),
        row.record!.note || "—",
      ]);

    if (progressRows.length > 0) {
      autoTable(doc, {
        head: [["Goal", "Baseline", "Current", "Mastery criterion", "Status", "Note"]],
        body: progressRows,
        startY: y,
        theme: "grid",
        styles: { fontSize: 7, cellPadding: 2, valign: "top", overflow: "linebreak" },
        headStyles: { fillColor: [5, 150, 105], textColor: 255, fontStyle: "bold" },
        columnStyles: {
          0: { cellWidth: 44 },
          1: { cellWidth: 22 },
          2: { cellWidth: 22 },
          3: { cellWidth: 34 },
          4: { cellWidth: 18 },
        },
        rowPageBreak: "avoid",
        margin: { left: 14, right: 14 },
      });
      y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 6;
      y += 4;
    } else {
      doc.setFontSize(9);
      doc.setTextColor(107, 114, 128);
      doc.text("No goal progress recorded.", 14, y);
      y += 8;
    }

    const droppedRows = goals
      .map((g) => ({ goal: g, record: g.id ? progressFor(goalProgress, g.id) : undefined }))
      .filter((row) => row.record?.dropped);
    if (droppedRows.length > 0) {
      y = ensureSpace(doc, y, 16);
      doc.setFont("helvetica", "bold");
      doc.setFontSize(8.5);
      doc.setTextColor(55, 65, 81);
      doc.text("Goals not requested this period:", 14, y);
      y += 4.5;
      doc.setFont("helvetica", "normal");
      doc.setTextColor(75, 85, 99);
      for (const row of droppedRows) {
        const text = `${row.goal.domain || "Goal"}: ${row.goal.description || "—"} — ${goalProgressStatusLabel(row.record!.status)}${row.record!.drop_reason ? ` (${row.record!.drop_reason})` : ""}`;
        const lines = doc.splitTextToSize(text, pageWidth - 28) as string[];
        for (const line of lines) {
          y = ensureSpace(doc, y, 5);
          doc.text(line, 14, y);
          y += 4.2;
        }
        y += 1.5;
      }
    }
    y += 2;
  }

  // --- Section 17: Assessment Graphs (plan-level attachments) ---
  // PNG and JPG graphs are embedded here, in the body of the document a reviewer
  // reads. Attached PDFs cannot be drawn onto this page, so they are listed here
  // and their pages are appended after this document by the caller. Every
  // attachment is named in the table either way, so the export still identifies
  // a file whose pages could not be merged.
  y = ensureSpace(doc, y, 30);
  y = addSectionTitle(doc, "Section 17: Attached Assessment Graphs", y + 2);
  if (attachments.length === 0) {
    doc.setFontSize(9);
    doc.setTextColor(107, 114, 128);
    doc.text("No assessment graphs attached.", 14, y);
    y += 8;
  } else {
    autoTable(doc, {
      head: [["Attachment", "Type", "Size", "In this export"]],
      body: attachments.map((a) => [
        a.filename || "—",
        a.mime_type === "application/pdf"
          ? "PDF"
          : a.mime_type === "image/png"
            ? "PNG"
            : "JPG",
        a.byte_size >= 1024 * 1024
          ? `${(a.byte_size / (1024 * 1024)).toFixed(1)} MB`
          : `${Math.max(1, Math.round(a.byte_size / 1024))} KB`,
        a.mime_type === "application/pdf"
          ? "Pages appended at the end"
          : "Graph reproduced below",
      ]),
      startY: y,
      theme: "grid",
      styles: { fontSize: 8, cellPadding: 2, valign: "top", overflow: "linebreak" },
      headStyles: { fillColor: [79, 70, 229], textColor: 255, fontStyle: "bold" },
      columnStyles: { 0: { cellWidth: 70 }, 1: { cellWidth: 16 }, 2: { cellWidth: 22 } },
      rowPageBreak: "avoid",
      margin: { left: 14, right: 14 },
    });
    y = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y + 6;
    y += 6;

    // Images, one per block: caption, then the graph scaled to the text width.
    for (const attachment of attachments) {
      if (attachment.mime_type === "application/pdf") continue;
      const bytes = attachmentBytes(attachment);
      const size = imagePixelSize(bytes);
      const maxWidth = pageWidth - 28;
      const maxHeight = 110;
      let drawWidth = maxWidth;
      let drawHeight = maxHeight;
      if (size) {
        const ratio = size.height / size.width;
        drawWidth = maxWidth;
        drawHeight = maxWidth * ratio;
        if (drawHeight > maxHeight) {
          drawHeight = maxHeight;
          drawWidth = maxHeight / ratio;
        }
      }
      y = ensureSpace(doc, y, Math.min(drawHeight, maxHeight) + 14);
      doc.setFont("helvetica", "bold");
      doc.setFontSize(9);
      doc.setTextColor(55, 65, 81);
      const caption = doc.splitTextToSize(
        attachment.filename || "Assessment graph",
        pageWidth - 28,
      ) as string[];
      doc.text(caption, 14, y);
      y += caption.length * 4.5;
      try {
        doc.addImage(
          `data:${attachment.mime_type};base64,${attachment.data_base64}`,
          attachment.mime_type === "image/png" ? "PNG" : "JPEG",
          14,
          y,
          drawWidth,
          drawHeight,
        );
        y += drawHeight + 8;
      } catch {
        // An image the PDF writer cannot decode is still named in the table above.
        doc.setFont("helvetica", "normal");
        doc.setFontSize(8);
        doc.setTextColor(107, 114, 128);
        doc.text("(This image could not be embedded.)", 14, y + 4);
        y += 12;
      }
    }
  }

  // --- Signature Block ---
  y = addSectionTitle(doc, "Signatures", Math.max(y + 4, doc.internal.pageSize.height - 70));
  const sigY = y + 10;
  doc.setDrawColor(156, 163, 175);
  doc.setLineWidth(0.3);

  // BCBA signature
  doc.line(14, sigY + 12, 90, sigY + 12);
  doc.setFontSize(8);
  doc.setTextColor(107, 114, 128);
  doc.text("BCBA Signature", 14, sigY + 16);

  // Date
  doc.line(14, sigY + 12, 90, sigY + 12); // line already drawn
  doc.text("Date", 14, sigY + 22);

  // Parent/Guardian signature
  doc.line(110, sigY + 12, 195, sigY + 12);
  doc.text("Parent / Guardian Signature", 110, sigY + 16);
  doc.text("Date", 110, sigY + 22);

  // --- Page footers ---
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    addPageFooter(doc, i, totalPages);
  }

  return doc.output("arraybuffer");
}

