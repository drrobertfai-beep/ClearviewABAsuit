function fmtDate(d: string | null | undefined): string {
  if (!d) return "—";
  return new Date(d).toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });
}

function parseJson<T>(val: unknown, fallback: T): T {
  if (Array.isArray(val)) return val as T;
  if (typeof val === "object" && val !== null) return val as T;
  return fallback;
}

function addPageFooter(doc: jsPDF, pageNum: number, totalPages: number) {
  const str = `Page ${pageNum} of ${totalPages} | Generated by ClearView ABA Suite | ${new Date().toLocaleString()}`;
  doc.setFontSize(8);
  doc.setTextColor(128, 128, 128);
  doc.text(str, 14, doc.internal.pageSize.height - 10, {
    align: "left",
  });
}

function addHeader(doc: jsPDF, title: string) {
  doc.setFontSize(10);
  doc.setTextColor(79, 70, 229); // indigo-600
  doc.text("ClearView ABA Suite", 14, 12);
  doc.setFontSize(16);
  doc.setTextColor(17, 24, 39); // gray-900
  doc.text(title, 14, 22);
  doc.setDrawColor(79, 70, 229);
  doc.setLineWidth(0.5);
  doc.line(14, 26, doc.internal.pageSize.width - 14, 26);
}

function addSectionTitle(doc: jsPDF, title: string, y: number): number {
  doc.setFontSize(12);
  doc.setTextColor(79, 70, 229);
  doc.setFont("helvetica", "bold");
  doc.text(title, 14, y);
  doc.setDrawColor(209, 213, 219);
  doc.setLineWidth(0.3);
  doc.line(14, y + 2, doc.internal.pageSize.width - 14, y + 2);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(17, 24, 39);
  return y + 8;
}

